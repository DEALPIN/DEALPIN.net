-- ===== 1-core.sql =====
-- Dealpin setup step 1-core. Safe to run again. Run the steps in order: 1, 2, 3, 4, then 5-verify.
-- NOTE: this step resets table and function permissions. If you ever run it again, run steps 2, 3 and 4 again afterwards.
-- Dealpin schema for Supabase (release 1.0). Run once in the SQL editor, then run supabase/storage.sql.
-- Tested by tests/schema.test.mjs on a real Postgres engine (PGlite) with stand-ins for auth and storage.
-- NOT yet run on a live Supabase project: do that on a staging project first.
--
-- Before use: create the private secret table (Step 4 of the setup guide): schema "private", table private.app_secrets,
-- row 'receipt_secret' generated by the database. Supabase does not allow custom database settings, so the secret lives
-- in a table that the public API roles cannot read. Without it no receipt code can be issued (the server refuses).
--
-- Access model
--   Seller  : signed in. Can read own deals, insert new ones, delete deals that never got a buyer.
--             Every other change goes through seller_act(). There is no UPDATE policy on deals.
--   Buyer   : no account. Holds buyer_token (in the link). buyer_get_deal / buyer_act only.
--   Rider   : no account. Holds rider_token (separate link). rider_get_deal / rider_act only.
--             The rider never sees the handover code, the buyer's payment, or the seller's numbers.
--   Public  : receipt, verify, seller record. Whitelisted fields only (see redact()).

create table if not exists profiles(
  id uuid primary key references auth.users on delete cascade,
  name text not null check(char_length(name) between 1 and 40),
  handle text unique not null check(handle ~ '^[a-z0-9-]{1,24}$'),
  phone text not null default '' check(char_length(phone)<=30),
  pay text not null default '' check(char_length(pay)<=80)
);

create table if not exists deals(
  id text primary key check(id ~ '^[a-z0-9]{10}$'),
  owner uuid not null references auth.users on delete cascade,
  buyer_token text not null unique check(buyer_token ~ '^[0-9a-f]{32}$'),
  rider_token text not null unique check(rider_token ~ '^[0-9a-f]{32}$'),
  -- Storage upload key for the buyer: SHA-256 of the token's 16 bytes, so file paths never reveal the token.
  buyer_key text generated always as (encode(sha256(decode(buyer_token,'hex')),'hex')) stored,
  status text not null check(status in ('created','agreed','shipped','received','disputed','cancelled','resolved')),
  created timestamptz not null default now(),
  doc jsonb not null check(jsonb_typeof(doc)='object' and pg_column_size(doc)<65536),
  check(buyer_token<>rider_token)
);
create index if not exists deals_owner_created_idx on deals(owner,created desc);
create index if not exists deals_code_idx on deals((doc->>'code'));
create index if not exists deals_buyer_key_idx on deals(buyer_key);

alter table profiles enable row level security;
alter table deals enable row level security;
drop policy if exists "own profile" on profiles;
create policy "own profile" on profiles for all to authenticated
  using(id=(select auth.uid())) with check(id=(select auth.uid()));
drop policy if exists "read own deals" on deals;
create policy "read own deals" on deals for select to authenticated using(owner=(select auth.uid()));
drop policy if exists "insert own deals" on deals;
create policy "insert own deals" on deals for insert to authenticated with check(owner=(select auth.uid()));
drop policy if exists "delete own deals" on deals;
create policy "delete own deals" on deals for delete to authenticated using(owner=(select auth.uid()));
-- No UPDATE policy on purpose: sellers change a deal only through seller_act().

-- ---------------------------------------------------------------- helpers
create or replace function jnn(j jsonb,k text) returns boolean language sql immutable as $$
  select coalesce(jsonb_typeof(j->k),'null')<>'null' $$;

create or replace function clean(t text,n int) returns text language sql immutable as $$
  select left(btrim(regexp_replace(coalesce(t,''),'[\x01-\x08\x0b\x0c\x0e-\x1f]','','g')),n) $$;

create or replace function dist_m(a1 float8,o1 float8,a2 float8,o2 float8) returns int language sql immutable as $$
  select round(12742000*asin(sqrt(least(1,power(sin(radians(a2-a1)/2),2)+cos(radians(a1))*cos(radians(a2))*power(sin(radians(o2-o1)/2),2)))))::int $$;

-- Rate limiting (counts per caller address per window). Private table: no policies, so nobody but the functions below can touch it.
create table if not exists rate(key text primary key,win bigint not null,n int not null,at timestamptz not null default now());
alter table rate enable row level security;

create or replace function who() returns text language plpgsql stable as $$
declare h json; x text;
begin
  h:=nullif(current_setting('request.headers',true),'')::json;
  x:=coalesce(h->>'cf-connecting-ip',nullif(btrim(split_part(coalesce(h->>'x-forwarded-for',''),',',-1)),''),'unknown');
  return left(x,64);
exception when others then return 'unknown'; end $$;

create or replace function bump(p_key text,p_secs int) returns int language plpgsql security definer set search_path=public as $$
declare w bigint:=floor(extract(epoch from now())/p_secs); c int;
begin
  insert into rate as r(key,win,n) values(p_key,w,1)
    on conflict(key) do update set n=case when r.win=excluded.win then r.n+1 else 1 end,win=excluded.win,at=now()
    returning n into c;
  if random()<0.01 then delete from rate where at<now()-interval '1 day'; end if;
  return c;
end $$;

create or replace function hit(p_scope text,p_max int,p_secs int) returns void language plpgsql security definer set search_path=public as $$
begin
  if bump(p_scope||':'||who(),p_secs)>p_max then raise exception 'Too many requests. Wait a minute and try again.'; end if;
end $$;

-- ---------------------------------------------------------------- what each role may see
-- Public (receipt, verify, seller record): whitelist only.
create or replace function redact(doc jsonb) returns jsonb language sql immutable as $$
  select jsonb_strip_nulls(jsonb_build_object(
    'id',doc->'id','title',doc->'title','price',doc->'price','currency',doc->'currency','delivery',doc->'delivery','status',doc->'status',
    'created',doc->'created','events',coalesce(doc->'events','[]'::jsonb),'code',doc->'code',
    'buyer',case when jnn(doc,'buyer') then jsonb_build_object('name',doc#>'{buyer,name}') end,
    'seller',jsonb_build_object('name',doc#>'{seller,name}','handle',doc#>'{seller,handle}'),
    'payment',case when jnn(doc,'payment') then jsonb_build_object('method',doc#>'{payment,method}','ok',doc#>'{payment,ok}') end,
    'rating',case when jnn(doc,'rating') then jsonb_build_object('stars',doc#>'{rating,stars}') end)) $$;

-- Rider: where to go and nothing else. No handover code, no payment, no seller numbers.
create or replace function rider_view(doc jsonb) returns jsonb language sql immutable as $$
  select jsonb_strip_nulls(jsonb_build_object(
    'id',doc->'id','title',doc->'title','status',doc->'status','delivery',doc->'delivery',
    'buyer',case when jnn(doc,'buyer') then jsonb_build_object('name',doc#>'{buyer,name}','phone',doc#>'{buyer,phone}',
              'pin',doc#>'{buyer,pin}','landmark',doc#>'{buyer,landmark}','voice',doc#>'{buyer,voice}') end,
    'arrival',doc->'arrival','handoverOk',doc->'handoverOk','needsHandover',coalesce(doc->>'handover','')<>'')) $$;

-- ---------------------------------------------------------------- checks on what a seller inserts
create or replace function guard_deal() returns trigger language plpgsql security definer set search_path=public as $$
declare n jsonb; k text; p profiles%rowtype; ms bigint:=(extract(epoch from now())*1000)::bigint;
begin
  if coalesce(current_setting('dealpin.act',true),'')='1' then
    if tg_op='DELETE' then return old; end if; return new;
  end if;
  if tg_op='DELETE' then
    if old.status not in('created','cancelled') then
      raise exception 'A deal that has a buyer is part of the record and cannot be deleted.'; end if;
    return old;
  end if;
  if tg_op='UPDATE' then raise exception 'Changes must go through the app.'; end if;
  n:=new.doc;
  if n->>'id' is distinct from new.id or n->>'status' is distinct from new.status or new.status<>'created' then
    raise exception 'A new deal must start as created.'; end if;
  foreach k in array array['buyer','code','rating','arrival','payment','dispute','handoverOk','handover','parcel'] loop
    if jnn(n,k) then raise exception 'Only the buyer can do that.'; end if; end loop;
  if jsonb_array_length(coalesce(n->'events','[]'))<>1 or n#>>'{events,0,s}' is distinct from 'created' then
    raise exception 'A new deal must start as created.'; end if;
  perform check_terms(n,new.owner);
  -- The server writes everything the seller must not choose: the seller's name, handle and numbers come from their profile,
  -- the time is the server's, and any other field in the document is dropped.
  select * into p from profiles where id=new.owner;
  if not found then raise exception 'Set up your seller profile first.'; end if;
  new.doc:=jsonb_strip_nulls(jsonb_build_object(
    'id',new.id,'title',clean(n->>'title',80),'price',n->'price','currency',n->>'currency','delivery',n->>'delivery',
    'terms',clean(n->>'terms',300),'photos',coalesce(n->'photos','[]'::jsonb),
    'seller',jsonb_build_object('name',p.name,'handle',p.handle,'phone',p.phone,'pay',p.pay),
    'status','created','created',ms,'events',jsonb_build_array(jsonb_build_object('s','created','at',ms))));
  return new;
end $$;
drop trigger if exists guard_deal on deals;
create trigger guard_deal before insert or update or delete on deals for each row execute function guard_deal();

-- What the seller writes: item, price, delivery, terms, photos (own uploaded files only).
create or replace function check_terms(n jsonb,p_owner uuid) returns void language plpgsql security definer set search_path=public as $$
begin
  if clean(n->>'title',80)='' or char_length(n->>'title')>80 then raise exception 'Enter what you are selling (up to 80 characters).'; end if;
  if jsonb_typeof(n->'price')<>'number' or (n->>'price')::numeric*1000<>trunc((n->>'price')::numeric*1000)
     or (n->>'price')::numeric<=0 or (n->>'price')::numeric>100000000000 then raise exception 'Enter a price above 0.'; end if;
  if coalesce(n->>'currency','') !~ '^[A-Z]{3}$' then raise exception 'Pick a currency.'; end if;
  if n->>'delivery' not in('I deliver by rider','Buyer collects','Courier or bus parcel') then raise exception 'Pick a delivery type.'; end if;
  if char_length(coalesce(n->>'terms',''))>300 then raise exception 'Terms are limited to 300 characters.'; end if;
  if jnn(n,'photos') then
    if jsonb_typeof(n->'photos')<>'array' or jsonb_array_length(n->'photos')>3 then raise exception 'Up to 3 photos.'; end if;
    if exists(select 1 from jsonb_array_elements_text(n->'photos') p where p !~ ('^s/'||p_owner||'/[0-9a-f]{32}\.jpg$')) then
      raise exception 'A photo is not one of your uploads.'; end if;
  end if;
end $$;

-- ---------------------------------------------------------------- public reads
create or replace function public_receipt(p_id text) returns jsonb language plpgsql security definer set search_path=public as $$
begin perform hit('rc',60,60); return (select redact(doc) from deals where id=p_id); end $$;

create or replace function public_verify(p_code text) returns jsonb language plpgsql security definer set search_path=public as $$
begin perform hit('vf',20,60);
  return (select redact(doc) from deals where doc->>'code'=upper(btrim(p_code)) limit 1); end $$;

create or replace function public_seller(p_handle text) returns jsonb language plpgsql security definer set search_path=public as $$
begin perform hit('sr',60,60);
  return (select jsonb_build_object('seller',jsonb_build_object('name',p.name,'handle',p.handle),
    'deals',coalesce((select jsonb_agg(redact(d.doc) order by d.created desc) from deals d
       where d.owner=p.id and d.status in('received','disputed','resolved')),'[]'::jsonb))
    from profiles p where p.handle=p_handle); end $$;

create or replace function buyer_get_deal(p_token text) returns jsonb language plpgsql security definer set search_path=public as $$
begin perform hit('tk',120,60); return (select doc from deals where buyer_token=p_token); end $$;

create or replace function rider_get_deal(p_token text) returns jsonb language plpgsql security definer set search_path=public as $$
begin perform hit('tk',120,60); return (select rider_view(doc) from deals where rider_token=p_token); end $$;

-- ---------------------------------------------------------------- shared step: append an event and save
create or replace function commit_deal(d deals,dd jsonb,st text,ev text) returns jsonb language plpgsql security definer set search_path=public as $$
declare ms bigint:=(extract(epoch from now())*1000)::bigint;
begin
  if jsonb_array_length(coalesce(dd->'events','[]'))>=60 then raise exception 'This deal has too many steps.'; end if;
  dd:=jsonb_set(dd||jsonb_build_object('status',st),'{events}',coalesce(dd->'events','[]'::jsonb)||jsonb_build_array(jsonb_build_object('s',ev,'at',ms)));
  perform set_config('dealpin.act','1',true);
  update deals set doc=dd,status=st where id=d.id;
  return dd;
end $$;

-- ---------------------------------------------------------------- buyer
create or replace function buyer_act(p_token text,p_action text,p_payload jsonb default '{}') returns jsonb language plpgsql security definer set search_path=public as $$
declare d deals%rowtype; dd jsonb; st text; ev text; pl jsonb:=coalesce(p_payload,'{}'::jsonb); ms bigint:=(extract(epoch from now())*1000)::bigint;
  b jsonb; nm text; ph text; lm text; vc text; pin jsonb; ph_ok text; h text; sec text; mth text; why text; photo text; stars int;
begin
  perform hit('tk',120,60);
  select * into d from deals where buyer_token=p_token for update;
  if not found then raise exception 'Deal not found.'; end if;
  dd:=d.doc; st:=d.status; ev:=p_action;

  if p_action='agree' and st='created' then
    b:=pl->'buyer'; nm:=clean(b->>'name',60); ph:=clean(b->>'phone',20); lm:=clean(b->>'landmark',200); vc:=nullif(b->>'voice','');
    if nm='' or ph='' then raise exception 'Enter your name and phone number.'; end if;
    if ph !~ '^[0-9+() -]{5,20}$' then raise exception 'Enter a valid phone number.'; end if;
    if vc is not null and vc !~ ('^b/'||d.buyer_key||'/[0-9a-f]{32}\.(webm|ogg|m4a)$') then raise exception 'That voice note is not valid.'; end if;
    if jsonb_typeof(b->'pin')='object' then
      if coalesce(b#>>'{pin,lat}','')!~'^-?[0-9]{1,3}(\.[0-9]+)?$' or coalesce(b#>>'{pin,lng}','')!~'^-?[0-9]{1,3}(\.[0-9]+)?$'
         or (b#>>'{pin,lat}')::float8 not between -90 and 90 or (b#>>'{pin,lng}')::float8 not between -180 and 180 then
        raise exception 'That location is not valid.'; end if;
      pin:=jsonb_build_object('lat',(b#>>'{pin,lat}')::float8,'lng',(b#>>'{pin,lng}')::float8,
            'acc',case when coalesce(b#>>'{pin,acc}','')~'^[0-9]{1,6}$' then (b#>>'{pin,acc}')::int else 0 end);
    end if;
    if dd->>'delivery'='I deliver by rider' and pin is null and lm='' and vc is null then raise exception 'Share your location or describe the place.'; end if;
    if dd->>'delivery'='Courier or bus parcel' and lm='' then raise exception 'Enter the town and bus park or courier office.'; end if;
    st:='agreed'; ev:='agreed';
    dd:=dd||jsonb_build_object('buyer',jsonb_build_object('name',nm,'phone',ph,'pin',pin,'landmark',lm,'voice',vc));

  elsif p_action='paid' and st in('agreed','shipped') and not jnn(dd,'payment') then
    mth:=pl#>>'{payment,method}';
    if mth is null or mth not in('Mobile money','Bank transfer','Card or online payment','Cash on delivery','Other','MTN MoMo','Airtel Money') then raise exception 'Pick how you paid.'; end if;
    dd:=dd||jsonb_build_object('payment',jsonb_build_object('method',mth,'ref',clean(pl#>>'{payment,ref}',40),'ok',false,'at',ms));

  elsif p_action='receive' and st='shipped' then
    select value into sec from private.app_secrets where name='receipt_secret'; sec:=coalesce(sec,'');
    if char_length(sec)<32 then raise exception 'The server is not set up to issue receipts yet.'; end if;
    h:=encode(sha256(convert_to(sec||'|'||d.id||'|'||(dd->>'title')||'|'||(dd->>'price')||'|'||coalesce(dd#>>'{buyer,name}','')||'|'||ms,'UTF8')),'hex');
    st:='received'; ev:='received';
    dd:=dd||jsonb_build_object('code',upper(substr(h,1,4)||'-'||substr(h,5,4)||'-'||substr(h,9,4)));

  elsif p_action='dispute' and st='shipped' then
    why:=clean(pl#>>'{dispute,why}',300); photo:=nullif(pl#>>'{dispute,photo}','');
    if why='' then raise exception 'Please say what is wrong.'; end if;
    if photo is not null and photo !~ ('^b/'||d.buyer_key||'/[0-9a-f]{32}\.jpg$') then raise exception 'That photo is not valid.'; end if;
    st:='disputed'; ev:='disputed';
    dd:=dd||jsonb_build_object('dispute',jsonb_build_object('why',why,'photo',photo));

  elsif p_action='rated' and st='received' and not jnn(dd,'rating') then
    if coalesce(pl#>>'{rating,stars}','')!~'^[1-5]$' then raise exception 'Pick 1 to 5 stars.'; end if;
    stars:=(pl#>>'{rating,stars}')::int;
    dd:=dd||jsonb_build_object('rating',jsonb_build_object('stars',stars,'text',clean(pl#>>'{rating,text}',200)));

  else raise exception 'That step is not allowed for this deal.'; end if;

  return commit_deal(d,dd,st,ev);
end $$;

-- ---------------------------------------------------------------- rider
create or replace function rider_act(p_token text,p_action text,p_payload jsonb default '{}') returns jsonb language plpgsql security definer set search_path=public as $$
declare d deals%rowtype; dd jsonb; pl jsonb:=coalesce(p_payload,'{}'::jsonb); ms bigint:=(extract(epoch from now())*1000)::bigint;
  la float8; lo float8; ac int; ds int; tries int;
begin
  perform hit('tk',120,60);
  select * into d from deals where rider_token=p_token for update;
  if not found then raise exception 'Deal not found.'; end if;
  dd:=d.doc;
  if d.status<>'shipped' then raise exception 'That step is not allowed for this deal.'; end if;

  if p_action='arrived' and not jnn(dd,'arrival') then
    if coalesce(pl#>>'{arrival,lat}','')!~'^-?[0-9]{1,3}(\.[0-9]+)?$' or coalesce(pl#>>'{arrival,lng}','')!~'^-?[0-9]{1,3}(\.[0-9]+)?$' then
      raise exception 'Your location is not valid.'; end if;
    la:=(pl#>>'{arrival,lat}')::float8; lo:=(pl#>>'{arrival,lng}')::float8;
    if la not between -90 and 90 or lo not between -180 and 180 then raise exception 'Your location is not valid.'; end if;
    ac:=case when coalesce(pl#>>'{arrival,acc}','')~'^[0-9]{1,6}$' then (pl#>>'{arrival,acc}')::int else 0 end;
    -- distance to the buyer's pin is worked out here, never taken from the rider's phone
    ds:=case when jnn(dd,'buyer') and jnn(dd->'buyer','pin') then dist_m((dd#>>'{buyer,pin,lat}')::float8,(dd#>>'{buyer,pin,lng}')::float8,la,lo) end;
    dd:=dd||jsonb_build_object('arrival',jsonb_build_object('lat',la,'lng',lo,'acc',ac,'dist',ds,'at',ms));
    return rider_view(commit_deal(d,dd,d.status,'arrived'));

  elsif p_action='handover' and coalesce(dd->>'handover','')<>'' and not jnn(dd,'handoverOk') then
    -- 4 digits can be guessed, so wrong codes are counted and the deal locks after 5 tries an hour
    tries:=bump('ho:'||d.id,3600);
    if tries>5 then raise exception 'Too many wrong codes. Try again in an hour or ask the seller.'; end if;
    if dd->>'handover' is distinct from (pl->>'handoverCode') then
      return jsonb_build_object('error','That code is not correct.'); end if;
    dd:=dd||jsonb_build_object('handoverOk',true);
    return rider_view(commit_deal(d,dd,d.status,'handover'));
  end if;
  raise exception 'That step is not allowed for this deal.';
end $$;

-- ---------------------------------------------------------------- seller (every change after the first insert)
create or replace function seller_act(p_id text,p_action text,p_payload jsonb default '{}') returns jsonb language plpgsql security definer set search_path=public as $$
declare d deals%rowtype; dd jsonb; st text; ev text; pl jsonb:=coalesce(p_payload,'{}'::jsonb); u uuid:=auth.uid(); t text; hc text;
begin
  if u is null then raise exception 'Please sign in.'; end if;
  select * into d from deals where id=p_id and owner=u for update;
  if not found then raise exception 'Deal not found.'; end if;
  dd:=d.doc; st:=d.status; ev:=p_action;

  if p_action='edit' and st='created' then
    dd:=dd||jsonb_build_object('title',clean(pl->>'title',80),'price',pl->'price','currency',pl->'currency','delivery',pl->'delivery','terms',clean(pl->>'terms',300),'photos',coalesce(pl->'photos','[]'::jsonb));
    perform check_terms(dd,u);
    perform set_config('dealpin.act','1',true);
    update deals set doc=dd where id=d.id;
    return dd||jsonb_build_object('bt',d.buyer_token,'rt',d.rider_token);
  elsif p_action='ship' and st='agreed' then
    st:='shipped'; ev:='shipped';
    t:=clean(pl->>'parcel',60);
    -- the rider handover code is made here, not by the seller's phone
    hc:=case when dd->>'delivery'='I deliver by rider' then (1000+(('x'||substr(replace(gen_random_uuid()::text,'-',''),1,7))::bit(28)::int % 9000))::text else '' end;
    dd:=dd||jsonb_build_object('parcel',t,'handover',hc);
  elsif p_action='cancel' and st in('created','agreed') then st:='cancelled'; ev:='cancelled';
  elsif p_action='payok' and jnn(dd,'payment') and (dd#>>'{payment,ok}')<>'true' and st in('agreed','shipped') then
    dd:=jsonb_set(dd,'{payment,ok}','true'::jsonb); ev:='payok';
  elsif p_action='reply' and st='disputed' and jnn(dd,'dispute') then
    t:=clean(pl->>'reply',300); if t='' then raise exception 'Write your reply first.'; end if;
    dd:=jsonb_set(dd,'{dispute,reply}',to_jsonb(t)); ev:='replied';
  elsif p_action='resolve' and st='disputed' then st:='resolved'; ev:='resolved';
  else raise exception 'That step is not allowed for this deal.'; end if;

  dd:=commit_deal(d,dd,st,ev);
  return dd||jsonb_build_object('bt',d.buyer_token,'rt',d.rider_token);
end $$;

-- ---------------------------------------------------------------- delete my account
-- Removes the profile and every deal (cascade). Receipts for those deals stop working.
-- The app deletes the uploaded files first (Storage cannot be emptied from SQL).
create or replace function delete_my_account() returns void language plpgsql security definer set search_path=public as $$
declare u uuid:=auth.uid();
begin
  if u is null then raise exception 'Please sign in.'; end if;
  perform set_config('dealpin.act','1',true);
  delete from auth.users where id=u;
end $$;

