/* Builds the website for speed:  node tools/build-site.js
   1. joins src/*.js into one file, js/site.js (one request instead of thirteen)
   2. pre-renders the home page into index.html so the first paint is already complete */
const fs=require('fs'),vm=require('vm'),path=require('path'),root=path.join(__dirname,'..');
const order=['core','page-home','page-how','page-features','page-tools','page-people','page-trust','page-faq','page-about','page-install','page-contact','page-signin','page-sellers','page-buyers','page-riders','page-explore','page-glossary','page-legal','router'];
const src=order.map(n=>fs.readFileSync(path.join(root,'src',n+'.js'),'utf8'));
fs.writeFileSync(path.join(root,'js/site.js'),'/* Generated by tools/build-site.js. Edit the files in src/ instead. */\n'+src.join('\n;\n'));
const ctx=vm.createContext({});ctx.window=ctx;
for(const n of order.slice(0,2))vm.runInContext(src[order.indexOf(n)],ctx);
const home=vm.runInContext('Pages.home.html()',ctx);
let h=fs.readFileSync(path.join(root,'index.html'),'utf8');
h=h.replace(/<!--PRE-->[\s\S]*?<!--\/PRE-->/,'<!--PRE-->'+home+'<!--/PRE-->');
const v=Date.now().toString(36);
h=h.replace(/(site\.css|js\/site\.js|js\/boot\.js)\?v=\w+/g,'$1?v='+v);
fs.writeFileSync(path.join(root,'index.html'),h);
console.log('built js/site.js',fs.statSync(path.join(root,'js/site.js')).size,'bytes; home pre-rendered',home.length,'bytes; version',v);
